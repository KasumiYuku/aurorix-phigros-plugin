pub fn portrait(size: i32) -> bool {
    size <= PORTRAIT_MAX
}

pub fn cols(size: i32) -> i32 {
    if portrait(size) {
        COLS_PORTRAIT
    } else {
        COLS_WIDE
    }
}

pub fn card_h(size: i32) -> f32 {
    if portrait(size) {
        CARD_H_PORTRAIT
    } else {
        CARD_H_WIDE
    }
}

pub fn margin(size: i32) -> f32 {
    if portrait(size) {
        MARGIN_PORTRAIT
    } else {
        MARGIN_WIDE
    }
}

pub fn col_gap(size: i32) -> f32 {
    if portrait(size) {
        COL_GAP_PORTRAIT
    } else {
        COL_GAP_WIDE
    }
}

pub fn row_gap(_size: i32) -> f32 {
    ROW_GAP
}

pub fn card_pad(size: i32) -> f32 {
    if portrait(size) {
        CARD_PAD_PORTRAIT
    } else {
        CARD_PAD_WIDE
    }
}

pub fn card_right_pad(size: i32) -> f32 {
    card_pad(size) - CARD_RIGHT_PAD_DELTA
}

pub fn card_title_gap(size: i32) -> f32 {
    if portrait(size) {
        CARD_TITLE_GAP_PORTRAIT
    } else {
        CARD_TITLE_GAP_WIDE
    }
}

pub fn width(size: i32) -> f32 {
    let columns = cols(size) as f32;
    2.0 * margin(size) + columns * CARD_W + (columns - 1.0) * col_gap(size)
}

pub fn rows(size: i32, count: i32) -> i32 {
    if count <= 0 {
        return 0;
    }
    let columns = cols(size);
    (count + columns - 1) / columns
}

pub fn player_bar_dy() -> f32 {
    PLATE_BAND_BOTTOM * 0.5
        - (player::player_bar().top() + player::player_bar().bottom()) / 2.0 * B30_SCALE
}

pub fn player_bar_bottom() -> f32 {
    let panel = player::panel_rect(0.0);
    let avatar = player::avatar_window();
    let bottom = panel.bottom().max(avatar.bottom());
    player_bar_dy() + bottom * B30_SCALE
}

pub fn top_band_top() -> f32 {
    player_bar_bottom() + TOP_BAND_GAP
}

pub fn grid_top(size: i32) -> f32 {
    let _ = size;
    top_band_top() + STATS_H + TOP_BAND_GAP
}

pub fn overflow_after_line(size: i32, entries: i32, podium: i32) -> i32 {
    if !portrait(size) || podium < 0 {
        return 0;
    }
    let podium = podium.min(COLS_PORTRAIT);
    let counted = podium + COUNTED_BEST;
    if entries <= counted {
        return 0;
    }
    (counted + COLS_PORTRAIT - 1) / COLS_PORTRAIT
}

pub fn overflow_extra(size: i32) -> f32 {
    if !portrait(size) {
        return 0.0;
    }
    OVERFLOW_GAP - row_gap(size)
}

pub fn overflow_top(size: i32, row_count: i32, after: i32) -> f32 {
    if after <= 0 || row_count <= after {
        return 0.0;
    }
    let above = grid_top(size)
        + (after - 1) as f32 * (card_h(size) + row_gap(size))
        + card_h(size);
    let shadow = CARD_SHADOW_STEPS as f32 * CARD_SHADOW_STEP_W;
    above + shadow + (OVERFLOW_GAP - shadow - OVERFLOW_BAR_H) / 2.0
}

pub fn height(size: i32, row_count: i32, after: i32) -> f32 {
    let row_count = row_count.max(1);
    let grid = row_count as f32 * card_h(size) + (row_count - 1) as f32 * row_gap(size);
    let mut out = grid_top(size) + grid + FOOTER_H;
    if after > 0 && row_count > after {
        out += overflow_extra(size);
    }
    out
}

pub fn out_width(size: i32) -> f32 {
    B30_OUT_W.max(width(size).round())
}

pub fn shrink(size: i32) -> f32 {
    out_width(size) / width(size).round()
}

pub fn out_size(size: i32, row_count: i32, after: i32) -> (i32, i32) {
    let factor = shrink(size);
    let w = (width(size).round() * factor).round() as i32;
    let h = (height(size, row_count, after).round() * factor).round() as i32;
    (w, h)
}

pub fn card_rect(index: i32, size: i32, after: i32) -> Rect {
    let index = index.max(0);
    let columns = cols(size);
    let mut y = grid_top(size) + (index / columns) as f32 * (card_h(size) + row_gap(size));
    if after > 0 && index / columns >= after {
        y += overflow_extra(size);
    }
    let x = margin(size) + (index % columns) as f32 * (CARD_W + col_gap(size));
    Rect::from_xywh(x, y, CARD_W, card_h(size))
}

pub fn stats_band(size: i32) -> Rect {
    Rect::from_xywh(
        margin(size),
        top_band_top(),
        width(size) - 2.0 * margin(size),
        STATS_H,
    )
}

pub fn stats_slot(index: i32, band: Rect) -> Rect {
    if !(0..STATS_COLS).contains(&index) {
        return Rect::from_xywh(0.0, 0.0, 0.0, 0.0);
    }
    let w = band.width() / STATS_COLS as f32;
    Rect::from_xywh(band.left() + index as f32 * w, band.top(), w, band.height())
}

pub fn stats_baseline(band: Rect) -> f32 {
    band.top() + band.height() / 2.0 + STATS_LIFT
}

pub fn footer_baseline(height_value: f32) -> f32 {
    let band = FOOTER_H;
    let ink = FOOT_SIZE * (FOOTER_INK_TOP + FOOTER_INK_BOTTOM);
    height_value - band + (band - ink) / 2.0 + FOOT_SIZE * FOOTER_INK_TOP
}

pub fn overflow_after(req: &B30Request) -> i32 {
    if req.no_tier {
        return 0;
    }
    let podium = req.entries.iter().filter(|entry| entry.podium).count() as i32;
    overflow_after_line(req.count, req.entries.len() as i32, podium)
}

pub fn title_text(req: &B30Request) -> String {
    if req.title.is_empty() {
        return format!("BEST {}", req.count);
    }
    req.title.clone()
}

