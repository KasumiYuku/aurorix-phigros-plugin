pub fn px(value: f32) -> i32 {
    (value + 0.5).floor() as i32
}

pub fn col_right(index: usize) -> f32 {
    let mut x = LIST_BASE_W - LIST_MARGIN_X - LIST_ROW_PAD;
    for width in LIST_COLS.iter().take(index) {
        x -= width + LIST_COL_GAP;
    }
    x
}

pub fn col_left(index: usize) -> f32 {
    if index >= LIST_COLS.len() {
        return 0.0;
    }
    col_right(index) - LIST_COLS[index]
}

pub fn col_count() -> usize {
    LIST_COLS.len()
}

