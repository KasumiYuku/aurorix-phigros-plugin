pub fn clamp_rows(rows: &[ListRow]) -> &[ListRow] {
    if rows.len() > LIST_HARD_ROWS {
        &rows[..LIST_HARD_ROWS]
    } else {
        rows
    }
}

pub fn groups(rows: &[ListRow]) -> Vec<ListGroupIn> {
    let mut out: Vec<ListGroupIn> = Vec::with_capacity(rows.len());
    for row in rows {
        match out.last_mut() {
            Some(group) if group.label == row.group => group.count += 1,
            _ => out.push(ListGroupIn {
                label: row.group.clone(),
                count: 1,
                tint: Difficulty::parse(row.diff.as_str()),
            }),
        }
    }
    out
}

pub fn plan_for(groups: &[ListGroupIn]) -> ListPlan {
    let total: usize = groups.iter().map(|group| group.count).sum();
    let two_col = total >= LIST_TWO_COL_ROWS;
    let columns = match two_col {
        true => 2.0,
        false => 1.0,
    };
    let row_h = match two_col {
        true => LIST_COMPACT_ROW_H,
        false => LIST_ROW_H,
    };
    let row_gap = match two_col {
        true => LIST_COMPACT_GAP,
        false => LIST_ROW_GAP,
    };
    let content = LIST_BASE_W - 2.0 * LIST_MARGIN_X;
    let row_w = match two_col {
        true => (content - LIST_TWO_COL_GAP) / 2.0,
        false => content,
    };
    let mut plan = ListPlan {
        w: LIST_BASE_W,
        h: 0.0,
        rows: Vec::with_capacity(total),
        sections: Vec::new(),
    };
    let mut y = LIST_GRID_TOP;
    for group in groups {
        if group.count == 0 {
            continue;
        }
        if !group.label.is_empty() {
            let base = y + LIST_SECTION_TOP + LIST_SECTION_SIZE;
            plan.sections.push(ListSection {
                label: group.label.clone(),
                note: format!("{} 条", group.count),
                tint: group.tint,
                base,
                rule_y: base + LIST_SECTION_RULE_GAP,
            });
            y = plan
                .sections
                .last()
                .map(|section| section.rule_y + LIST_RULE_H + LIST_SECTION_GAP)
                .unwrap_or(y);
        }
        for k in 0..group.count {
            let line = (k as f32 / columns).floor();
            let col = k as f32 % columns;
            plan.rows.push(Rect::from_xywh(
                LIST_MARGIN_X + col * (row_w + LIST_TWO_COL_GAP),
                y + line * (row_h + row_gap),
                row_w,
                row_h,
            ));
        }
        let lines = (group.count as f32 / columns).ceil();
        y += lines * (row_h + row_gap);
    }
    plan.h = (y - row_gap).max(LIST_GRID_TOP) + LIST_FOOTER_H;
    plan
}

pub fn plan(req: &ListRequest) -> ListPlan {
    plan_for(&groups(&req.rows))
}

pub fn last_bottom(plan: &ListPlan) -> f32 {
    match plan.rows.last() {
        None => LIST_GRID_TOP,
        Some(row) => row.bottom(),
    }
}

pub fn is_long(plan: &ListPlan) -> bool {
    plan.rows.len() > LIST_LONG_ROWS
}

